using System.Text;
using System.Text.Json.Nodes;
using WinMarchy.Core.Themes;

namespace WinMarchy.Core.Integrations;

/// <summary>
/// Starship's prompt in PowerShell 7 and Fastfetch's system information, in the theme's colours.
/// Their settings live in C:\WinMarchy\Runtime, so a starship.toml or Fastfetch config of the user's
/// own stays as it is. The PowerShell profile only gets WinMarchy's marked block, which loads the
/// prompt script if it is there.
/// </summary>
public static class ShellExtras
{
    /// <summary>Omarchy's prompt (directory, Git branch and status, ❯), with the accent instead of cyan.</summary>
    public static string StarshipToml(Palette p)
    {
        var accent = ColorMath.Legible(p.Accent, p.Background, 3.0);
        var error = ColorMath.Legible(p.Red, p.Background, 3.0);
        var muted = p.DarkForeground;
        return $$"""
            # Written by WinMarchy from the Omarchy theme "{{p.Name}}". The next theme overwrites it.
            add_newline = true
            command_timeout = 200
            format = "$directory$git_branch$git_status$character"

            [character]
            success_symbol = "[❯](bold {{accent}})"
            error_symbol = "[✗](bold {{error}})"

            [directory]
            truncation_length = 2
            truncation_symbol = "…/"
            style = "{{muted}}"
            repo_root_style = "bold {{accent}}"
            repo_root_format = "[$repo_root]($repo_root_style)[$path]($style)[$read_only]($read_only_style) "
            read_only = " ro"

            [git_branch]
            format = "[$branch]($style) "
            style = "italic {{accent}}"

            [git_status]
            format = "[$all_status$ahead_behind]($style)"
            style = "{{accent}}"
            ahead = "⇡${count} "
            behind = "⇣${count} "
            diverged = "⇕⇡${ahead_count}⇣${behind_count} "
            conflicted = "= "
            untracked = "? "
            modified = "! "
            staged = "+ "
            renamed = "» "
            deleted = "✘ "
            stashed = ""
            up_to_date = ""

            """.Replace("\r\n", "\n");
    }

    /// <summary>
    /// What a new PowerShell tab starts with, dot-sourced by the profile block: Fastfetch's system
    /// information (also as the command "fastfetch" with WinMarchy's settings), then Starship's
    /// prompt. Fastfetch stays out of scripts (-File, -Command) and of VS Code's PowerShell
    /// extension. Under AppLocker PowerShell runs in constrained language mode; Fastfetch still
    /// shows there, Starship's script cannot run and the plain prompt stays.
    /// </summary>
    public static string ShellScript(string? starshipExe, string? fastfetchExe)
    {
        static string Q(string s) => "'" + s.Replace("'", "''") + "'";
        var sb = new StringBuilder();
        void Line(string text) => sb.Append(text).Append("\r\n");
        Line("# Generated by WinMarchy: what a new PowerShell tab starts with, in the colours of the current Omarchy theme.");
        Line("$winmarchyFull = $ExecutionContext.SessionState.LanguageMode -eq 'FullLanguage'");
        if (fastfetchExe != null)
        {
            Line($"if (Test-Path -LiteralPath {Q(fastfetchExe)}) {{");
            Line($"  function fastfetch {{ & {Q(fastfetchExe)} --config {Q(Paths.FastfetchConfig)} @args }}");
            Line("  $winmarchyTab = $Host.Name -eq 'ConsoleHost'");
            // Only readable in full language mode; there scripts started with -File or -Command stay quiet.
            Line("  if ($winmarchyTab -and $winmarchyFull -and ([Environment]::GetCommandLineArgs() -match '^[-/](c|com\\w*|f|fil\\w*|e|ec|enc\\w*|noni\\w*)$')) { $winmarchyTab = $false }");
            Line("  if ($winmarchyTab) { fastfetch }");
            Line("}");
        }
        if (starshipExe != null)
        {
            Line($"if ($winmarchyFull -and (Test-Path -LiteralPath {Q(starshipExe)})) {{");
            Line($"  $env:STARSHIP_CONFIG = {Q(Paths.StarshipConfig)}");
            Line($"  try {{ Invoke-Expression (& {Q(starshipExe)} init powershell --print-full-init | Out-String) }} catch {{ }}");
            Line("}");
        }
        return sb.ToString();
    }

    /// <summary>
    /// Fastfetch's settings: the Windows logo in the theme's colours, then the machine, and the
    /// terminal colours at the end, as in Omarchy's "About".
    /// </summary>
    public static string FastfetchConfig(Palette p)
    {
        static string Sgr(string hex)
        {
            var (r, g, b) = ColorMath.Rgb(hex);
            return $"38;2;{r};{g};{b}";
        }
        var accent = Sgr(ColorMath.Legible(p.Accent, p.Background, 3.0));
        JsonObject Module(string type, string key) => new() { ["type"] = type, ["key"] = L.T("fastfetch." + key) };
        var root = new JsonObject
        {
            ["logo"] = new JsonObject
            {
                ["type"] = "builtin",
                ["source"] = "windows",
                ["color"] = new JsonObject { ["1"] = accent, ["2"] = Sgr(p.Cyan), ["3"] = Sgr(p.Green), ["4"] = Sgr(p.Yellow) },
            },
            ["display"] = new JsonObject
            {
                ["separator"] = "  ",
                ["color"] = new JsonObject { ["keys"] = accent, ["title"] = accent },
            },
            ["modules"] = new JsonArray
            {
                "title", "separator",
                Module("os", "os"), Module("host", "host"), Module("kernel", "kernel"), Module("uptime", "uptime"),
                Module("shell", "shell"), Module("terminal", "terminal"), Module("display", "display"),
                Module("cpu", "cpu"), Module("gpu", "gpu"), Module("memory", "memory"), Module("disk", "disk"),
                Module("battery", "battery"),
                // The address in use (the one of the default route) with its network card's MAC, for IT tickets.
                new JsonObject
                {
                    ["type"] = "localip", ["key"] = L.T("fastfetch.localip"), ["showIpv4"] = true, ["showMac"] = true,
                    ["showPrefixLen"] = false, ["defaultRouteOnly"] = true,
                },
                Module("locale", "locale"),
                "break", "colors",
            },
        };
        return "// Written by WinMarchy from the Omarchy theme \"" + p.Name + "\". The next theme overwrites it.\n" + Json.Format(root) + "\n";
    }

    /// <summary>
    /// Starship and Fastfetch, whichever is installed (null: not): their settings in the theme's
    /// colours, the start script, and the profile block that loads it.
    /// </summary>
    public static void Apply(IntegrationContext ctx, Palette palette, string? starshipExe, string? fastfetchExe)
    {
        if (starshipExe == null && fastfetchExe == null) return;
        if (starshipExe != null) ctx.WriteFile(Paths.StarshipConfig, StarshipToml(palette));
        if (fastfetchExe != null) ctx.WriteFile(Paths.FastfetchConfig, FastfetchConfig(palette));
        ctx.WriteFile(Paths.ShellScript, ShellScript(starshipExe, fastfetchExe), bom: true);
        var profiles = TerminalTheme.EnsureProfileHook(ctx);
        ctx.Report(profiles.Count > 0 ? L.T("integrations.shell.done", ("path", string.Join(" · ", profiles))) : L.T("integrations.shell.noProfile"));
    }
}

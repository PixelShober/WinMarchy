using System.Text;
using System.Text.Json.Nodes;
using WinMarchy.Core.Themes;

namespace WinMarchy.Core.Integrations;

/// <summary>
/// Starship's prompt in PowerShell 7 and Fastfetch's system information, in the theme's colours.
/// Their settings live in C:\WinMarchy\Runtime, so a starship.toml or Fastfetch config of the user's
/// own stays as it is. The PowerShell profile only gets WinMarchy's marked block, which loads the
/// prompt script if it is there.
/// </summary>
public static class ShellExtras
{
    /// <summary>Omarchy's prompt (directory, Git branch and status, ❯), with the accent instead of cyan.</summary>
    public static string StarshipToml(Palette p)
    {
        var accent = ColorMath.Legible(p.Accent, p.Background, 3.0);
        var error = ColorMath.Legible(p.Red, p.Background, 3.0);
        var muted = p.DarkForeground;
        return $$"""
            # Written by WinMarchy from the Omarchy theme "{{p.Name}}". The next theme overwrites it.
            add_newline = true
            command_timeout = 200
            format = "$directory$git_branch$git_status$character"

            [character]
            success_symbol = "[❯](bold {{accent}})"
            error_symbol = "[✗](bold {{error}})"

            [directory]
            truncation_length = 2
            truncation_symbol = "…/"
            style = "{{muted}}"
            repo_root_style = "bold {{accent}}"
            repo_root_format = "[$repo_root]($repo_root_style)[$path]($style)[$read_only]($read_only_style) "
            read_only = " ro"

            [git_branch]
            format = "[$branch]($style) "
            style = "italic {{accent}}"

            [git_status]
            format = "[$all_status$ahead_behind]($style)"
            style = "{{accent}}"
            ahead = "⇡${count} "
            behind = "⇣${count} "
            diverged = "⇕⇡${ahead_count}⇣${behind_count} "
            conflicted = "= "
            untracked = "? "
            modified = "! "
            staged = "+ "
            renamed = "» "
            deleted = "✘ "
            stashed = ""
            up_to_date = ""

            """.Replace("\r\n", "\n");
    }

    /// <summary>
    /// Loads Starship into PowerShell 7. Under AppLocker PowerShell runs in constrained language
    /// mode, where Starship's script cannot work; then the plain prompt stays.
    /// </summary>
    public static string PromptScript(string starshipExe, string config)
    {
        static string Q(string s) => "'" + s.Replace("'", "''") + "'";
        var sb = new StringBuilder();
        sb.Append("# Generated by WinMarchy: Starship's prompt in the colours of the current Omarchy theme.\r\n");
        sb.Append("if ($ExecutionContext.SessionState.LanguageMode -eq 'FullLanguage') {\r\n");
        sb.Append($"  $winmarchyStarship = {Q(starshipExe)}\r\n");
        sb.Append("  if (Test-Path -LiteralPath $winmarchyStarship) {\r\n");
        sb.Append($"    $env:STARSHIP_CONFIG = {Q(config)}\r\n");
        sb.Append("    try { Invoke-Expression (& $winmarchyStarship init powershell --print-full-init | Out-String) } catch { }\r\n");
        sb.Append("  }\r\n}\r\n");
        return sb.ToString();
    }

    /// <summary>
    /// Fastfetch's settings: the Windows logo in the theme's colours, then the machine, and the
    /// terminal colours at the end, as in Omarchy's "About".
    /// </summary>
    public static string FastfetchConfig(Palette p)
    {
        static string Sgr(string hex)
        {
            var (r, g, b) = ColorMath.Rgb(hex);
            return $"38;2;{r};{g};{b}";
        }
        var accent = Sgr(ColorMath.Legible(p.Accent, p.Background, 3.0));
        JsonObject Module(string type, string key) => new() { ["type"] = type, ["key"] = L.T("fastfetch." + key) };
        var root = new JsonObject
        {
            ["logo"] = new JsonObject
            {
                ["type"] = "builtin",
                ["source"] = "windows",
                ["color"] = new JsonObject { ["1"] = accent, ["2"] = Sgr(p.Cyan), ["3"] = Sgr(p.Green), ["4"] = Sgr(p.Yellow) },
            },
            ["display"] = new JsonObject
            {
                ["separator"] = "  ",
                ["color"] = new JsonObject { ["keys"] = accent, ["title"] = accent },
            },
            ["modules"] = new JsonArray
            {
                "title", "separator",
                Module("os", "os"), Module("host", "host"), Module("kernel", "kernel"), Module("uptime", "uptime"),
                Module("shell", "shell"), Module("terminal", "terminal"), Module("display", "display"),
                Module("cpu", "cpu"), Module("gpu", "gpu"), Module("memory", "memory"), Module("disk", "disk"),
                Module("battery", "battery"), Module("locale", "locale"),
                "break", "colors",
            },
        };
        return "// Written by WinMarchy from the Omarchy theme \"" + p.Name + "\". The next theme overwrites it.\n" + Json.Format(root) + "\n";
    }

    /// <summary>Starship installed: its settings, the prompt script and the profile block that loads it.</summary>
    public static void ApplyStarship(IntegrationContext ctx, Palette palette, string starshipExe)
    {
        ctx.WriteFile(Paths.StarshipConfig, StarshipToml(palette));
        ctx.WriteFile(Paths.PromptScript, PromptScript(starshipExe, Paths.StarshipConfig), bom: true);
        if (TerminalTheme.EnsureProfileHook(ctx)) ctx.Report(L.T("integrations.starship.done"));
    }

    public static void ApplyFastfetch(IntegrationContext ctx, Palette palette)
    {
        ctx.WriteFile(Paths.FastfetchConfig, FastfetchConfig(palette));
        ctx.Report(L.T("integrations.fastfetch.done"));
    }

    /// <summary>Theme change: new colours for whichever of the two is set up.</summary>
    public static void ApplyTheme(IntegrationContext ctx, Palette palette)
    {
        if (File.Exists(Paths.StarshipConfig)) ctx.WriteFile(Paths.StarshipConfig, StarshipToml(palette));
        if (File.Exists(Paths.FastfetchConfig)) ctx.WriteFile(Paths.FastfetchConfig, FastfetchConfig(palette));
    }
}

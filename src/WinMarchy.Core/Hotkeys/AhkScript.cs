using System.Text;

namespace WinMarchy.Core.Hotkeys;

/// <summary>What the generated AutoHotkey script needs to know about this machine.</summary>
/// <param name="LeaveAlone">Keys another program owns (Greenshot's Print keys), normalized: no hotkey for them.</param>
/// <param name="Extra">Shortcuts a setting adds when their keys are free (Greenshot takes Win+Shift+S).</param>
public sealed record AhkContext(string WinMarchyExe, string GlazeCli, bool WinKeyOpensLauncher, string LauncherKeys = "!{F24}",
    IReadOnlyCollection<string>? LeaveAlone = null, IReadOnlyList<HotkeyBinding>? Extra = null);

/// <summary>
/// Generates the AutoHotkey v2 script from the active shortcuts. Only fixed function calls with quoted
/// string literals end up in the script, never user text as code.
/// </summary>
public static class AhkScript
{
    public const string AgentTitle = "WinMarchy Agent";

    public static string Generate(HotkeySet set, AhkContext ctx)
    {
        var sb = new StringBuilder();
        sb.AppendLine("; Generated by WinMarchy – changes here are overwritten. Edit shortcuts in WinMarchy → Hotkeys.");
        sb.AppendLine("#Requires AutoHotkey v2.0");
        sb.AppendLine("#SingleInstance Force");
        sb.AppendLine("#NoTrayIcon");
        sb.AppendLine("SetTitleMatchMode 3");
        sb.AppendLine("A_MenuMaskKey := \"vkE8\"");
        sb.AppendLine($"global AgentTitle := {Quote(AgentTitle)}");
        sb.AppendLine($"global WinMarchyExe := {Quote(ctx.WinMarchyExe)}");
        sb.AppendLine($"global GlazeCli := {Quote(ctx.GlazeCli)}");
        sb.AppendLine($"global LauncherKeys := {Quote(ctx.LauncherKeys)}");
        sb.AppendLine();

        if (ctx.WinKeyOpensLauncher)
        {
            sb.AppendLine("Hotkey(\"~LWin\", WinDown)");
            sb.AppendLine("Hotkey(\"~LWin Up\", WinUp)");
        }

        var taken = set.Active.Select(b => b.Keys).ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (var b in set.Active.Concat(ctx.Extra?.Where(x => !taken.Contains(x.Keys)) ?? Enumerable.Empty<HotkeyBinding>()))
        {
            if (b.Combo is not { } combo || b.Action is not { } action) continue;
            if (ctx.LeaveAlone?.Contains(combo.ToString()) == true) continue;
            sb.Append("Hotkey(").Append(Quote(combo.ToAhk())).Append(", (*) => ").Append(Call(action, ctx))
              .Append(")  ; ").AppendLine(Comment(b.Describe()));
        }

        sb.AppendLine();
        sb.Append(Runtime());
        return sb.ToString();
    }

    static string Call(HotkeyAction action, AhkContext ctx) => action.Kind switch
    {
        ActionKind.Send => KeyCombo.TryParse(action.Value, out var c, out _) ? $"Send({Quote(c.ToAhkSend())})" : "0",
        ActionKind.App when action.Value == "launcher" => "Send(LauncherKeys)",
        ActionKind.Do when action.Value == "copy" => "UniversalCopy()",
        ActionKind.Do when action.Value == "paste" => "UniversalPaste()",
        _ => $"Act({Quote(action.ToString())})",
    };

    /// <summary>AutoHotkey v2 string literal: backtick escapes, nothing else is special inside quotes.</summary>
    public static string Quote(string value) =>
        "\"" + value.Replace("`", "``").Replace("\"", "`\"").Replace("\r", "`r").Replace("\n", "`n") + "\"";

    static string Comment(string text) => text.Replace("\r", " ").Replace("\n", " ");

    public static string Runtime()
    {
        using var stream = typeof(AhkScript).Assembly.GetManifestResourceStream("WinMarchy.Hotkeys.runtime.ahk")
            ?? throw new InvalidOperationException("runtime.ahk is not embedded");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }
}
